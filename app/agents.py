class PresentationAgent:
    def __init__(self, llm: BaseChatModel, tools: List[BaseTool], retriever: Optional[BaseRetriever] = None):
        self.llm = llm
        self.tools = tools
        self.retriever = retriever
        self.system_prompt = """You are an expert presentation creation assistant. Your primary goal is to generate a detailed, structured plan (in JSON format) for a PowerPoint presentation based on the user's input content and style request.

You must use the available tools to achieve this.

Follow these steps:
1. Analyze the user's input content and the requested presentation style and template name.
2. Use the 'Bullet_Points_Generator' tool to create a detailed, structured JSON outline for the presentation.
   - This tool will generate a JSON containing metadata and a list of slides.
   - Each slide should have a title, slide type, and a list of `content_elements` (which can be text, tables, charts, or image placeholders).
   - The tool should leverage documentation context (RAG) to make informed decisions about structuring elements like tables and charts and suggesting appropriate slide layouts based on python-pptx capabilities.
   - The generated JSON must conform to the specific schema expected by the tool.
3. (Optional) If complex content analysis or quality feedback is needed, use the 'Presentation_Quality_Checker' tool to analyze the generated structure JSON. Incorporate feedback if it improves the outline.
4. Your *final* output MUST be the structured presentation JSON (as a raw string) generated by the 'Bullet_Points_Generator' tool (potentially refined based on quality check). Do not add any explanatory text, markdown formatting (like ```json), or commentary before or after the JSON object itself.

Example Interaction:
User: Convert this text about Q1 sales figures into a professional presentation using the 'professional' template. Text: [Sales data included]
Agent: (Thinking: I need to structure this data. Sales figures suggest tables and maybe a summary chart. I'll use Bullet_Points_Generator with style 'Professional' and template 'professional'. It should use RAG to help structure the table/chart JSON correctly.)
Agent -> Bullet_Points_Generator (content="...", style="Professional", template_name="professional")
Tool <- (Returns detailed JSON structure string: {"metadata": ..., "slides": [{"title": "...", "content_elements": [{"element_type": "text", ...}, {"element_type": "table", ...}]}, ...]})
Agent: (Thinking: The structure includes text and a table. Looks good. This JSON string is the final output.)
Agent -> Final Answer: {"metadata": ..., "slides": [{"title": "...", "content_elements": [{"element_type": "text", ...}, {"element_type": "table", ...}]}, ...]}
"""
        self.prompt = ChatPromptTemplate.from_messages([
            SystemMessage(content=self.system_prompt),
            MessagesPlaceholder(variable_name="chat_history"),
            ("user", "{input}"),
            MessagesPlaceholder(variable_name="agent_scratchpad")
        ])

        self.agent_runnable: Runnable = create_react_agent(
            model=self.llm,
            tools=self.tools,
            prompt=self.prompt,
            # messages_modifier=SystemMessage(content=self.system_prompt)
        )
        logger.info(
            f"PresentationAgent initialized with LLM: {llm.__class__.__name__} and Tools: {[t.name for t in tools]}. RAG Retriever: {'Provided' if retriever else 'Not Provided'}")

    def run(self, user_input: str, style: str, template_name: str, config: Optional[RunnableConfig] = None) -> Dict[str, Any]:
        """
        Executes the presentation creation process using the ReAct agent.

        Args:
            user_input (str): The raw text content from the user.
            style (str): The conceptual style requested (e.g., Professional, Creative).
            template_name (str): The specific template name (e.g., professional, creative).
            config (Optional[RunnableConfig]): Optional Langchain runnable config.

        Returns:
            Dict[str, Any]: The final structured presentation JSON produced by the agent.

        Raises:
            ValueError: If the agent fails to produce a valid JSON output or the JSON lacks expected structure.
            RuntimeError: For other agent execution errors.
        """
        logger.info(f"Running PresentationAgent with style='{style}', template='{template_name}'")
        agent_input_message = f"""
        Please generate a detailed presentation structure based on the following content.
        Presentation Style: {style}
        Visual Template Name: {template_name}

        Content:
        ---
        {user_input}
        ---
        """

        agent_response = None
        try:
            agent_input = {"input": agent_input_message, "chat_history": []}
            effective_config = config or RunnableConfig()
            agent_response = self.agent_runnable.invoke(agent_input, config=effective_config)

            final_response_content = None
            if isinstance(agent_response, dict) and "output" in agent_response:
                final_response_content = agent_response["output"]
            elif isinstance(agent_response, dict) and "messages" in agent_response and isinstance(
                    agent_response["messages"], list) and agent_response["messages"]:
                last_message = agent_response["messages"][-1]
                if hasattr(last_message, 'content'):
                    final_response_content = last_message.content
                elif isinstance(last_message, str):
                    final_response_content = last_message

            if not final_response_content or not isinstance(final_response_content, str):
                logger.error(
                    f"Agent execution finished but produced no recognizable string output. Response: {agent_response}")
                raise ValueError("Agent produced no parsable string output.")

            logger.debug(f"Agent raw output string:\n{final_response_content[:500]}...")

            cleaned_json_string = final_response_content.strip()
            if cleaned_json_string.startswith("```json"):
                cleaned_json_string = cleaned_json_string[7:].strip()
                if cleaned_json_string.endswith("```"):
                    cleaned_json_string = cleaned_json_string[:-3].strip()
            elif cleaned_json_string.startswith("```"):
                cleaned_json_string = cleaned_json_string[3:].strip()
                if cleaned_json_string.endswith("```"):
                    cleaned_json_string = cleaned_json_string[:-3].strip()

            try:
                presentation_json = json.loads(cleaned_json_string)
                logger.info("Successfully parsed agent's final output as JSON.")

                if not isinstance(presentation_json, dict):
                    raise ValueError("Agent output is JSON but not a dictionary (object).")
                if "slides" not in presentation_json:
                    raise ValueError("Agent output JSON is missing the required 'slides' key.")
                if not isinstance(presentation_json.get("slides"), list):
                    raise ValueError("Agent output JSON 'slides' key is not a list.")
                if presentation_json.get("slides"):
                    first_slide = presentation_json["slides"][0]
                    if not isinstance(first_slide, dict):
                        logger.warning("First slide in agent JSON is not a dictionary.")
                    elif "content_elements" not in first_slide:
                        logger.warning("First slide in agent JSON might be missing 'content_elements'.")

                return presentation_json

            except json.JSONDecodeError as json_err:
                logger.error(f"Failed to parse agent's final output as JSON: {json_err}")
                logger.error(f"Agent raw output that failed parsing (after cleaning):\n{cleaned_json_string}")
                error_context = cleaned_json_string[:200] + "..." if len(
                    cleaned_json_string) > 200 else cleaned_json_string
                raise ValueError(
                    f"Agent did not return valid JSON. Error: {json_err}. Output started with: {error_context}") from json_err

        except Exception as e:
            if isinstance(e, ValueError) and (
                    "Agent produced no parsable string output." in str(e) or
                    "Agent did not return valid JSON." in str(e) or
                    "Agent output is JSON but not a dictionary" in str(e) or
                    "Agent output JSON is missing the required 'slides' key." in str(e) or
                    "Agent output JSON 'slides' key is not a list." in str(e)
            ):
                raise e

            logger.error(f"An unexpected error occurred during PresentationAgent execution: {e}", exc_info=True)
            raise RuntimeError(f"An unexpected error occurred in the agent: {e}") from e


def get_llm_instance(llm_provider: str, api_key: str) -> BaseChatModel:
    """Helper function to get LLM instance."""
    try:
        if llm_provider.lower() == "openai":
            return ChatOpenAI(api_key=api_key, model="gpt-4-turbo", temperature=0.1,
                              max_tokens=4096)
        elif llm_provider.lower() == "anthropic":
            return ChatAnthropic(api_key=api_key, model_name="claude-3-5-sonnet-20240620", temperature=0.1,
                                 max_tokens=4096)
        else:
            raise ValueError(f"Unsupported LLM provider: {llm_provider}")
    except Exception as e:
        logger.error(f"Failed to initialize LLM for provider {llm_provider}: {e}")
        raise


def create_agent(llm_provider: str, api_key: str, loaded_docs: Optional[List[Document]] = None) -> PresentationAgent:
    """
    Creates the PresentationAgent with configured LLM and tools, optionally setting up RAG.

    Args:
        llm_provider (str): "OpenAI" or "Anthropic".
        api_key (str): The API key for the chosen provider.
        loaded_docs (Optional[List[Document]]): Pre-loaded documents for RAG context.

    Returns:
        PresentationAgent: The initialized agent instance.
    """
    llm = get_llm_instance(llm_provider, api_key)

    retriever: Optional[BaseRetriever] = None
    if loaded_docs:
        try:
            logger.info(f"Initializing RAG system with {len(loaded_docs)} documents for context.")
            rag_system = EnhancedRAG(docs=loaded_docs, cache_name="pptx_docs_structure_elements")
            retriever = rag_system.get_retriever(k=4)
            if retriever:
                logger.info("RAG retriever successfully created.")
            else:
                logger.warning("RAG system initialized but failed to create a retriever.")
        except Exception as rag_setup_err:
            logger.error(f"Failed to initialize RAG system: {rag_setup_err}", exc_info=True)
            retriever = None
    else:
        logger.info("No documents provided for RAG context.")

    bullet_points_tool_func: Callable[[Dict], str] = partial(
        run_bullet_points_tool_with_llm, llm=llm, retriever=retriever
    )
    bullet_points_tool_description = (create_bullet_points_tool.__doc__ or
                                      "Generates a detailed, structured JSON presentation outline (including text, tables, charts) "
                                      "from text, optionally using documentation context (RAG) for element structuring and layout suggestions.")

    bullet_points_tool = BaseTool.from_function(
        func=bullet_points_tool_func,
        name="Bullet_Points_Generator",
        description=bullet_points_tool_description.strip(),
        args_schema=BulletPointInput
    )

    quality_check_tool_func: Callable[[Dict], str] = partial(
        run_quality_check_tool_with_llm, llm=llm
    )
    quality_check_tool_description = (create_quality_check_tool.__doc__ or
                                      "Analyzes a detailed presentation structure JSON (with various elements) for quality, "
                                      "clarity, flow, and engagement, providing feedback.")

    quality_check_tool = BaseTool.from_function(
        func=quality_check_tool_func,
        name="Presentation_Quality_Checker",
        description=quality_check_tool_description.strip(),
        args_schema=QualityCheckInput
    )

    tools = [
        bullet_points_tool,
        quality_check_tool
    ]
    return PresentationAgent(llm=llm, tools=tools, retriever=retriever)


def run_bullet_points_tool_with_llm(tool_input: Dict[str, Any], llm: BaseChatModel,
                                    retriever: Optional[BaseRetriever]) -> str:
    """Helper to run the bullet points logic with injected LLM and Retriever."""
    try:
        validated_input = BulletPointInput(**tool_input)
        return create_bullet_points_tool(validated_input, llm, retriever)
    except Exception as e:
        logger.error(f"Error running Bullet_Points_Generator tool logic: {e}", exc_info=True)
        return f"Error executing Bullet_Points_Generator: Failed to generate structure - {e}"


def run_quality_check_tool_with_llm(tool_input: Dict[str, Any], llm: BaseChatModel) -> str:
    """Helper to run the quality check logic with injected LLM."""
    try:
        validated_input = QualityCheckInput(**tool_input)
        if not isinstance(validated_input.presentation_structure, dict):
            return "Error executing Presentation_Quality_Checker: Input 'presentation_structure' must be a valid JSON object/dictionary."
        return create_quality_check_tool(validated_input, llm)
    except Exception as e:
        logger.error(f"Error running Presentation_Quality_Checker tool logic: {e}", exc_info=True)
        return f"Error executing Presentation_Quality_Checker: Failed to perform analysis - {e}"
