class PresentationAgent:
    def __init__(self, llm: BaseChatModel, tools: List[BaseTool], retriever: Optional[BaseRetriever] = None):
        self.llm = llm
        self.tools = tools
        self.retriever = retriever
        self.system_prompt = """You are an expert presentation creation assistant. Your primary goal is to generate a structured plan (in JSON format) for a PowerPoint presentation based on the user's input content and style request.

You must use the available tools to achieve this.

Follow these steps:
1. Analyze the user's input content and the requested presentation style and template name.
2. Use the 'Bullet_Points_Generator' tool to create a detailed, structured JSON outline for the presentation. This tool might use documentation context (RAG) to improve suggestions. The JSON should include slide titles, bullet points, slide types, speaker notes, and layout/design suggestions based on the specified template.
3. (Optional) If you deem it necessary for complex content or if quality feedback is requested, use the 'Presentation_Quality_Checker' tool to analyze the generated structure. Incorporate feedback if it improves the presentation outline.
4. Your *final* output MUST be the structured presentation JSON generated by the 'Bullet_Points_Generator' tool (potentially after refinement based on quality check). Do not add any explanatory text, markdown formatting (like ```json), or commentary before or after the JSON object itself.

Example Interaction:
User: Convert this text about climate change into a professional presentation using the 'professional' template. Text: [...]
Agent: (Thinking: I need to structure this content. I'll use the Bullet_Points_Generator tool with style 'Professional' and template 'professional'. It might use RAG.)
Agent -> Bullet_Points_Generator (content="...", style="Professional", template_name="professional")
Tool <- (Returns JSON structure string: {"metadata": ..., "slides": [...]})
Agent: (Thinking: The structure looks good. This JSON string is the final output.)
Agent -> Final Answer: {"metadata": ..., "slides": [...]}
"""
        self.prompt = ChatPromptTemplate.from_messages([
            SystemMessage(content=self.system_prompt),
            MessagesPlaceholder(variable_name="chat_history"),
            ("user", "{input}"),
            MessagesPlaceholder(variable_name="agent_scratchpad")
        ])

        self.agent_runnable: Runnable = create_react_agent(
            llm=self.llm,
            tools=self.tools,
            messages_modifier=self.prompt
        )
        logger.info(
            f"PresentationAgent initialized with LLM: {llm.__class__.__name__} and Tools: {[t.name for t in tools]}. RAG Retriever: {'Provided' if retriever else 'Not Provided'}")

    def run(self, user_input: str, style: str, template_name: str, config: Optional[RunnableConfig] = None) -> Dict[
        str, Any]:
        """
        Executes the presentation creation process using the ReAct agent.

        Args:
            user_input (str): The raw text content from the user.
            style (str): The conceptual style requested (e.g., Professional, Creative).
            template_name (str): The specific template name (e.g., professional, creative).
            config (Optional[RunnableConfig]): Optional Langchain runnable config.

        Returns:
            Dict[str, Any]: The final structured presentation JSON produced by the agent.

        Raises:
            ValueError: If the agent fails to produce a valid JSON output.
            Exception: For other agent execution errors.
        """
        logger.info(f"Running PresentationAgent with style='{style}', template='{template_name}'")
        agent_input_message = f"""
        Please generate a presentation structure based on the following content.
        Presentation Style: {style}
        Visual Template Name: {template_name}

        Content:
        ---
        {user_input}
        ---
        """

        try:
            agent_input = {"input": agent_input_message, "chat_history": []}
            effective_config = config or RunnableConfig()
            # effective_config = RunnableConfig(configurable={"llm": self.llm, "retriever": self.retriever})
            agent_response = self.agent_runnable.invoke(agent_input, config=effective_config)

            final_response_content = None
            if isinstance(agent_response, dict):
                if "output" in agent_response:
                    final_response_content = agent_response["output"]
                elif "messages" in agent_response and isinstance(agent_response["messages"], list) and agent_response["messages"]:
                    last_message = agent_response["messages"][-1]
                    if hasattr(last_message, 'content'):
                        final_response_content = last_message.content

            if not final_response_content:
                logger.error(
                    f"Agent execution finished but produced no recognizable output or final message content. Response: {agent_response}")
                raise ValueError("Agent produced no parsable output.")

            logger.debug(f"Agent raw output string:\n{final_response_content[:500]}...")
            if final_response_content.strip().startswith("```json"):
                final_response_content = final_response_content.strip()[7:-3].strip()
            elif final_response_content.strip().startswith("```"):
                final_response_content = final_response_content.strip()[3:-3].strip()

            try:
                presentation_json = json.loads(final_response_content)
                logger.info("Successfully parsed agent's final output as JSON.")
                if not isinstance(presentation_json, dict) or "slides" not in presentation_json:
                    logger.warning("Agent output parsed as JSON, but lacks expected 'slides' key.")
                    raise ValueError("Agent output is JSON but not the expected presentation structure.")
                return presentation_json
            except json.JSONDecodeError as json_err:
                logger.error(f"Failed to parse agent's final output as JSON: {json_err}")
                logger.error(
                    f"Agent raw output that failed parsing (after stripping fences):\n{final_response_content}")
                raise ValueError(f"Agent did not return valid JSON as expected. Error: {json_err}")

        except Exception as e:
            logger.error(f"Error during PresentationAgent execution: {e}", exc_info=True)
            raise


def get_llm_instance(llm_provider: str, api_key: str) -> BaseChatModel:
    """Helper function to get LLM instance."""
    try:
        if llm_provider.lower() == "openai":
            return ChatOpenAI(api_key=api_key, model="gpt-4-turbo", temperature=0.1,
                              max_tokens=4000)
        elif llm_provider.lower() == "anthropic":
            return ChatAnthropic(api_key=api_key, model_name="claude-3-sonnet-20240229", temperature=0.1,
                                 max_tokens=4000)
        else:
            raise ValueError(f"Unsupported LLM provider: {llm_provider}")
    except Exception as e:
        logger.error(f"Failed to initialize LLM for provider {llm_provider}: {e}")
        raise


def create_agent(llm_provider: str, api_key: str, loaded_docs: Optional[List[Document]] = None) -> PresentationAgent:
    """
    Creates the PresentationAgent with configured LLM and tools, optionally setting up RAG.

    Args:
        llm_provider (str): "OpenAI" or "Anthropic".
        api_key (str): The API key for the chosen provider.
        loaded_docs (Optional[List[Document]]): Pre-loaded documents for RAG context.

    Returns:
        PresentationAgent: The initialized agent instance.
    """
    llm = get_llm_instance(llm_provider, api_key)

    retriever: Optional[BaseRetriever] = None
    if loaded_docs:
        try:
            logger.info(f"Initializing RAG system with {len(loaded_docs)} documents for context.")
            rag_system = EnhancedRAG(docs=loaded_docs, cache_name="pptx_docs_structure")
            retriever = rag_system.get_retriever(k=3)  # Get 3 context chunks
            if retriever:
                logger.info("RAG retriever successfully created.")
            else:
                logger.warning("RAG system initialized but failed to create a retriever.")
        except Exception as rag_setup_err:
            logger.error(f"Failed to initialize RAG system: {rag_setup_err}", exc_info=True)
            retriever = None
    else:
        logger.info("No documents provided for RAG context.")

    # Tool Creation with Dependency Injection
    bullet_points_tool_func: Callable[[Dict], str] = partial(
        run_bullet_points_tool_with_llm, llm=llm, retriever=retriever  # Pass retriever
    )
    bullet_points_tool = BaseTool.from_function(
        func=bullet_points_tool_func,
        name="Bullet_Points_Generator",
        description=create_bullet_points_tool.__doc__ or "Generates a structured JSON presentation outline from text, optionally using documentation context.",
        args_schema=BulletPointInput
    )
    quality_check_tool_func: Callable[[Dict], str] = partial(
        run_quality_check_tool_with_llm, llm=llm
    )
    quality_check_tool = BaseTool.from_function(
        func=quality_check_tool_func,
        name="Presentation_Quality_Checker",
        description=create_quality_check_tool.__doc__ or "Analyzes a presentation structure JSON for quality and provides feedback.",
        args_schema=QualityCheckInput
    )

    tools = [
        bullet_points_tool,
        quality_check_tool
    ]
    return PresentationAgent(llm=llm, tools=tools, retriever=retriever)


def run_bullet_points_tool_with_llm(tool_input: Dict[str, Any], llm: BaseChatModel,
                                    retriever: Optional[BaseRetriever]) -> str:
    """Helper to run the bullet points logic with injected LLM and Retriever."""
    try:
        validated_input = BulletPointInput(**tool_input)
        return create_bullet_points_tool(validated_input, llm, retriever)
    except Exception as e:
        logger.error(f"Error running Bullet_Points_Generator tool: {e}", exc_info=True)
        return f"Error executing Bullet_Points_Generator: {e}"


def run_quality_check_tool_with_llm(tool_input: Dict[str, Any], llm: BaseChatModel) -> str:
    """Helper to run the quality check logic with injected LLM."""
    try:
        validated_input = QualityCheckInput(**tool_input)
        return create_quality_check_tool(validated_input, llm)
    except Exception as e:
        logger.error(f"Error running Presentation_Quality_Checker tool: {e}", exc_info=True)
        return f"Error executing Presentation_Quality_Checker: {e}"
